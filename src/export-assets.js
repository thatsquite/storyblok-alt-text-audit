import "dotenv/config";
import fs from "node:fs/promises";

const token = process.env.STORYBLOK_MANAGEMENT_TOKEN?.trim();
const spaceId = process.env.STORYBLOK_SPACE_ID?.trim();
const region = process.env.STORYBLOK_REGION?.trim().toLowerCase() || "eu";

if (!token || !spaceId) {
  throw new Error(
    "Missing STORYBLOK_MANAGEMENT_TOKEN or STORYBLOK_SPACE_ID in .env",
  );
}

const baseUrls = {
  eu: "https://mapi.storyblok.com",
  us: "https://api-us.storyblok.com",
  ca: "https://api-ca.storyblok.com",
  ap: "https://api-ap.storyblok.com",
};

const baseUrl = baseUrls[region];

if (!baseUrl) {
  throw new Error(`Unsupported Storyblok region: ${region}`);
}

const perPage = 100;
const allAssets = [];

const delay = (milliseconds) =>
  new Promise((resolve) => setTimeout(resolve, milliseconds));

async function fetchAssetPage(page, attempt = 1) {
  const url =
    `${baseUrl}/v1/spaces/${spaceId}/assets/` +
    `?page=${page}&per_page=${perPage}`;

  const response = await fetch(url, {
    headers: {
      Authorization: token,
      Accept: "application/json",
    },
  });

  if (response.status === 429) {
    const maxAttempts = 5;

    if (attempt >= maxAttempts) {
      const details = await response.text();

      throw new Error(
        `Asset request failed after ${maxAttempts} attempts ` +
          `on page ${page}: 429 Too Many Requests\n${details}`,
      );
    }

    const retryAfterHeader = response.headers.get("retry-after");
    const retryAfterSeconds = Number(retryAfterHeader);

    const waitMilliseconds =
      Number.isFinite(retryAfterSeconds) && retryAfterSeconds > 0
        ? retryAfterSeconds * 1000
        : attempt * 2000;

    console.log(
      `Rate limit reached on page ${page}. ` +
        `Retrying attempt ${attempt + 1} after ` +
        `${waitMilliseconds / 1000} seconds.`,
    );

    await delay(waitMilliseconds);

    return fetchAssetPage(page, attempt + 1);
  }

  if (!response.ok) {
    const details = await response.text();

    throw new Error(
      `Asset request failed on page ${page}: ` +
        `${response.status} ${response.statusText}\n${details}`,
    );
  }

  const data = await response.json();

  return {
    assets: data.assets ?? [],
    total: Number(response.headers.get("total") ?? 0),
  };
}

console.log("Retrieving Storyblok assets...");

let page = 1;
let totalAssets = 0;

while (true) {
  const result = await fetchAssetPage(page);

  if (page === 1) {
    totalAssets = result.total;

    console.log(
      totalAssets > 0
        ? `Storyblok reports ${totalAssets} assets.`
        : "Total asset count was not available in the response headers.",
    );
  }

  allAssets.push(...result.assets);

  console.log(`Page ${page}: ${result.assets.length} assets retrieved.`);

  if (result.assets.length < perPage) {
    break;
  }

  page += 1;

  /*
   * Keep normal traffic below Storyblok's API rate limit.
   */
  await delay(250);
}

/*
 * Load the folder paths generated by build-folder-paths.js.
 */
const folderPathRaw = await fs.readFile("output/folder-paths.json", "utf8");

const folderPathData = JSON.parse(folderPathRaw);

const folderPaths = folderPathData.folder_paths ?? [];

const folderPathsById = new Map(
  folderPaths.map((folder) => [folder.id, folder.full_path]),
);

function normalizeText(...values) {
  for (const value of values) {
    if (typeof value === "string" && value.trim()) {
      return value.trim();
    }
  }

  return "";
}

function parseDimensions(size) {
  if (typeof size !== "string") {
    return {
      width: null,
      height: null,
    };
  }

  const match = size.trim().match(/^(\d+)\s*x\s*(\d+)$/i);

  if (!match) {
    return {
      width: null,
      height: null,
    };
  }

  return {
    width: Number(match[1]),
    height: Number(match[2]),
  };
}

function getFileExtension(filename) {
  if (typeof filename !== "string") {
    return "";
  }

  const cleanFilename = filename.split("?")[0];
  const lastPart = cleanFilename.split("/").pop() ?? "";
  const dotPosition = lastPart.lastIndexOf(".");

  if (dotPosition === -1) {
    return "";
  }

  return lastPart.slice(dotPosition + 1).toLowerCase();
}

function classifyAltStatus(assetAlt, metadataAlt) {
  const normalizedAlt = normalizeText(assetAlt, metadataAlt);

  if (!normalizedAlt) {
    return "Missing alt text";
  }

  return "Existing alt text";
}

const inventory = allAssets.map((asset) => {
  const dimensions = parseDimensions(asset.meta_data?.size);

  const assetAlt = typeof asset.alt === "string" ? asset.alt.trim() : "";

  const metadataAlt =
    typeof asset.meta_data?.alt === "string" ? asset.meta_data.alt.trim() : "";

  const normalizedAlt = normalizeText(assetAlt, metadataAlt);

  const normalizedTitle = normalizeText(asset.title, asset.meta_data?.title);

  const normalizedCopyright = normalizeText(
    asset.copyright,
    asset.meta_data?.copyright,
  );

  const folderPath = asset.asset_folder_id
    ? (folderPathsById.get(asset.asset_folder_id) ?? "")
    : "";

  return {
    asset_id: asset.id,
    space_id: asset.space_id,
    filename: asset.short_filename ?? "",
    asset_url: asset.filename ?? "",
    file_extension: getFileExtension(asset.short_filename ?? asset.filename),
    mime_type: asset.content_type ?? "",
    file_size_bytes: asset.content_length ?? null,
    width: dimensions.width,
    height: dimensions.height,
    folder_id: asset.asset_folder_id,
    folder_path: folderPath,
    asset_alt: assetAlt,
    metadata_alt: metadataAlt,
    normalized_alt: normalizedAlt,
    alt_status: classifyAltStatus(assetAlt, metadataAlt),
    title: normalizedTitle,
    copyright: normalizedCopyright,
    source: normalizeText(asset.source, asset.meta_data?.source),
    tags: asset.internal_tags_list ?? [],
    tag_ids: asset.internal_tag_ids ?? [],
    focus: asset.focus ?? "",
    is_private: Boolean(asset.is_private),
    locked: Boolean(asset.locked),
    created_at: asset.created_at ?? null,
    updated_at: asset.updated_at ?? null,
    publish_at: asset.publish_at ?? null,
    expire_at: asset.expire_at ?? null,
    deleted_at: asset.deleted_at ?? null,
    folder_mapping_status:
      asset.asset_folder_id === null
        ? "Root folder"
        : folderPath
          ? "Resolved"
          : "Unresolved folder",
  };
});

const imageAssets = inventory.filter((asset) =>
  asset.mime_type.startsWith("image/"),
);

const missingAltAssets = imageAssets.filter(
  (asset) => asset.alt_status === "Missing alt text",
);

const unresolvedFolders = inventory.filter(
  (asset) => asset.folder_mapping_status === "Unresolved folder",
);

const rootFolderAssets = inventory.filter(
  (asset) => asset.folder_mapping_status === "Root folder",
);

const summary = {
  generated_at: new Date().toISOString(),
  space_id: Number(spaceId),
  assets_retrieved: inventory.length,
  storyblok_reported_total: totalAssets || null,
  asset_total_matches:
    totalAssets > 0 ? inventory.length === totalAssets : null,
  image_assets: imageAssets.length,
  images_with_missing_alt_text: missingAltAssets.length,
  images_with_existing_alt_text: imageAssets.length - missingAltAssets.length,
  assets_in_root_folder: rootFolderAssets.length,
  assets_with_unresolved_folders: unresolvedFolders.length,
};

await fs.mkdir("output", {
  recursive: true,
});

await fs.writeFile(
  "output/assets-inventory.json",
  JSON.stringify(
    {
      summary,
      assets: inventory,
    },
    null,
    2,
  ),
  "utf8",
);

console.log("");
console.log("Asset inventory completed.");
console.log(`Assets retrieved: ${summary.assets_retrieved}`);
console.log(
  `Storyblok reported total: ` +
    `${summary.storyblok_reported_total ?? "Unavailable"}`,
);
console.log(
  `Asset total matches: ` + `${summary.asset_total_matches ?? "Not checked"}`,
);
console.log(`Image assets: ${summary.image_assets}`);
console.log(
  `Images missing alt text: ` + `${summary.images_with_missing_alt_text}`,
);
console.log(
  `Images with existing alt text: ` +
    `${summary.images_with_existing_alt_text}`,
);
console.log(`Assets in root folder: ` + `${summary.assets_in_root_folder}`);
console.log(
  `Assets with unresolved folders: ` +
    `${summary.assets_with_unresolved_folders}`,
);
console.log("Saved to output/assets-inventory.json");
